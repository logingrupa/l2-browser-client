import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { rotatorSineFromTable } from "../../src/shared/math/rotator";
import { rotatorVector } from "../../src/environment/model/lightmapRebuild/rotatorVector";
import { worldLightRadius } from "../../src/environment/model/lightmapRebuild/worldLightRadius";

interface RadiusFixture {
  readonly map: string;
  readonly lightRadius: number;
  readonly result: number;
  readonly resultBits: string;
}

interface RotationFixture {
  readonly object: string;
  readonly effect: number;
  readonly rotation: readonly [pitch: number, yaw: number, roll: number];
  readonly returnedRotation: readonly [pitch: number, yaw: number, roll: number];
  readonly vectorBytesHex: string;
}

interface RadiusRotationDocument {
  readonly controlWord: string;
  readonly sineTable: { readonly entries: number; readonly sha256: string };
  readonly radiusFixtures: readonly RadiusFixture[];
  readonly rotationFixtures: readonly RotationFixture[];
}

const document = JSON.parse(readFileSync(new URL("../fixtures/db16/radius-rotation-native.json", import.meta.url), "utf8")) as RadiusRotationDocument;

function float32BitsHex(value: number): string {
  const view = new DataView(new ArrayBuffer(4));
  view.setFloat32(0, value);
  return `0x${view.getUint32(0).toString(16).padStart(8, "0")}`;
}

function littleEndianFloat32Hex(values: readonly number[]): string {
  const view = new DataView(new ArrayBuffer(values.length * 4));
  values.forEach((value, index) => view.setFloat32(index * 4, value, true));
  return Buffer.from(view.buffer).toString("hex");
}

describe("FGlobalMath sine table 0x1014d330 generated by the shared rotator port", () => {
  it("hashes to the native CW 0x027f table dump", () => {
    const entries = Float32Array.from({ length: document.sineTable.entries }, (_, entry) => rotatorSineFromTable(entry * 4));
    expect(createHash("sha256").update(new Uint8Array(entries.buffer)).digest("hex")).toBe(document.sineTable.sha256);
  });
});

describe("ALight::WorldLightRadius 0x10343130 against native runs", () => {
  it("covers every authored radius of the effect 0, 8 and 12 shadow records on 20_10 and 20_20", () => {
    expect(document.controlWord).toBe("0x027f");
    expect(document.radiusFixtures.filter(fixture => fixture.map === "20_10")).toHaveLength(12);
    expect(document.radiusFixtures.filter(fixture => fixture.map === "20_20")).toHaveLength(13);
  });

  it.each(document.radiusFixtures.map(fixture => [fixture.map, fixture.lightRadius, fixture] as const))("%s LightRadius %s", (_map, _lightRadius, fixture) => {
    expect(float32BitsHex(worldLightRadius(fixture.lightRadius))).toBe(fixture.resultBits);
    expect(worldLightRadius(fixture.lightRadius)).toBe(fixture.result);
  });
});

describe("GetViewRotation and FRotator::Vector 0x10110a10 against the authored 20_10 spotlights", () => {
  it("returns the actor rotation unchanged for every light", () => {
    expect(document.rotationFixtures).toHaveLength(8);
    expect(document.rotationFixtures.every(fixture => fixture.returnedRotation.every((units, axis) => units === fixture.rotation[axis]))).toBe(true);
  });

  it.each(document.rotationFixtures.map(fixture => [fixture.object, fixture] as const))("matches the vector bytes of %s", (_object, fixture) => {
    const [pitch, yaw, roll] = fixture.rotation;
    expect(littleEndianFloat32Hex(rotatorVector({ pitch, yaw, roll }))).toBe(fixture.vectorBytesHex);
  });
});
